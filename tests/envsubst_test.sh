#!/usr/bin/env bash
# Unit test for private/envsubst.bash, the pure-bash envsubst the wrappers
# use to expand dev_url_template. Runs with PATH cleared, so it also proves
# no host tool is involved.
set -euo pipefail

# shellcheck disable=SC1090
source "$1"
PATH=/nonexistent

fails=0
check() {
  local name="$1" template="$2" want="$3" got
  got="$(envsubst "$template")"
  if [[ "$got" != "$want" ]]; then
    printf 'FAIL %s\n  template: %s\n  want:     %s\n  got:      %s\n' \
      "$name" "$template" "$want" "$got" >&2
    fails=$((fails + 1))
  else
    printf 'ok   %s\n' "$name"
  fi
}

export PGUSER=app PGHOST=127.0.0.1 PGPORT=54321 PGDATABASE=dev
# Autogenerated-password shape: every character eval would trip over.
export PGPASSWORD='p$a`s"s'"'"'w;o|r&d$(x)${y}\n*'
unset UNSET_VAR || true

check default_template \
  'postgresql://${PGUSER}:${PGPASSWORD}@${PGHOST}:${PGPORT}/${PGDATABASE}?sslmode=disable' \
  "postgresql://app:${PGPASSWORD}@127.0.0.1:54321/dev?sslmode=disable"
check bare_names '$PGHOST:$PGPORT' '127.0.0.1:54321'
check name_ends_at_non_word '$PGUSER-x/${PGUSER}y' 'app-x/appy'
check unset_is_empty 'a${UNSET_VAR}b$UNSET_VAR.c' 'ab.c'
check lone_dollar 'cost $5 and $ and ${ and $PGPORT$' 'cost $5 and $ and ${ and 54321$'
check no_vars 'sqlite://?mode=memory&_fk=1' 'sqlite://?mode=memory&_fk=1'
check empty '' ''
check value_not_reexpanded '${PGPASSWORD}' "$PGPASSWORD"
check adjacent '${PGUSER}${PGPORT}$PGHOST' 'app54321127.0.0.1'

if (( fails )); then
  echo "$fails case(s) failed" >&2
  exit 1
fi
